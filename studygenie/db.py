"""SQLite storage for StudyGenie.

Tables:
  users        — accounts (email, password hash); each user's data is isolated
  courses      — one row per class (name, exam date, owner)
  topics       — study topics inside a course, each with a difficulty 1-5
  sessions     — planned/completed study blocks generated by the scheduler
  availability — minutes available per weekday, per user

Ownership root is courses.user_id; topics and sessions inherit ownership
through their course. Every read/write below takes user_id and enforces it.
"""
import sqlite3
from datetime import date, timedelta
from pathlib import Path

from werkzeug.security import generate_password_hash

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TEXT DEFAULT (datetime('now'))
);
CREATE TABLE IF NOT EXISTS courses (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    exam_date TEXT NOT NULL,          -- YYYY-MM-DD
    created_at TEXT DEFAULT (date('now'))
);
CREATE TABLE IF NOT EXISTS topics (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    difficulty INTEGER NOT NULL DEFAULT 3 CHECK (difficulty BETWEEN 1 AND 5),
    done INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    topic_id INTEGER REFERENCES topics(id) ON DELETE SET NULL,
    planned_date TEXT NOT NULL,       -- YYYY-MM-DD
    minutes INTEGER NOT NULL,
    completed INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS availability (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    minutes INTEGER NOT NULL DEFAULT 60 CHECK (minutes >= 0),
    PRIMARY KEY (user_id, weekday)
);
"""


def migrate(db_path):
    """Bring an older database up to the current schema.

    - Creates the users table.
    - Adds courses.user_id (existing rows keep NULL = orphan).
    - Rebuilds availability as per-user (preserving existing rows as
      orphan rows with user_id NULL is impossible under the new PK, so
      existing availability rows are kept under a sentinel and adopted
      with the orphan courses).
    Safe to run on an already-current database.
    """
    with connect(db_path) as conn:
        conn.execute(
            "CREATE TABLE IF NOT EXISTS users ("
            " id INTEGER PRIMARY KEY AUTOINCREMENT,"
            " email TEXT NOT NULL UNIQUE,"
            " password_hash TEXT NOT NULL,"
            " created_at TEXT DEFAULT (datetime('now')))"
        )
        cols = [r["name"] for r in
                conn.execute("PRAGMA table_info(courses)").fetchall()]
        if "user_id" not in cols:
            conn.execute(
                "ALTER TABLE courses ADD COLUMN user_id INTEGER"
                " REFERENCES users(id) ON DELETE CASCADE")
        # availability: rebuild only if still the old single-user shape
        conn.execute(
            "CREATE TABLE IF NOT EXISTS _orphan_availability ("
            " weekday INTEGER PRIMARY KEY, minutes INTEGER NOT NULL)")
        avail_cols = [r["name"] for r in
                      conn.execute("PRAGMA table_info(availability)").fetchall()]
        if avail_cols and "user_id" not in avail_cols:
            old = conn.execute(
                "SELECT weekday, minutes FROM availability").fetchall()
            conn.execute("DROP TABLE availability")
            conn.execute(
                "CREATE TABLE availability ("
                " user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,"
                " weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),"
                " minutes INTEGER NOT NULL DEFAULT 60 CHECK (minutes >= 0),"
                " PRIMARY KEY (user_id, weekday))")
            # old rows have no owner; stash them for orphan adoption
            for r in old:
                conn.execute(
                    "INSERT INTO _orphan_availability (weekday, minutes)"
                    " VALUES (?, ?)"
                    " ON CONFLICT(weekday) DO UPDATE"
                    " SET minutes=excluded.minutes",
                    (r["weekday"], r["minutes"]))


def adopt_orphans(db_path, user_id):
    """Give pre-account data (courses + availability) to a new user.

    Called once when the first account is created and orphan rows exist.
    """
    with connect(db_path) as conn:
        conn.execute(
            "UPDATE courses SET user_id = ? WHERE user_id IS NULL", (user_id,))
        for r in conn.execute("SELECT weekday, minutes FROM _orphan_availability"):
            conn.execute(
                "INSERT INTO availability (user_id, weekday, minutes)"
                " VALUES (?, ?, ?)"
                " ON CONFLICT(user_id, weekday) DO NOTHING",
                (user_id, r["weekday"], r["minutes"]))
        conn.execute("DELETE FROM _orphan_availability")


def connect(db_path):
    """Open a connection with foreign keys and WAL mode enabled.

    WAL lets readers proceed while a write is in progress and makes
    crash recovery robust — the right journal mode for a small
    multi-user deployment on one server.
    """
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        conn.execute("PRAGMA journal_mode = WAL")
    except sqlite3.OperationalError:
        pass  # e.g. read-only contexts; rollback journal still works
    return conn


def init_db(db_path):
    with connect(db_path) as conn:
        conn.executescript(SCHEMA)


# --- users ---

def add_user(db_path, email, password_hash):
    """Create a user; returns id. Raises sqlite3.IntegrityError on dup email."""
    with connect(db_path) as conn:
        cur = conn.execute(
            "INSERT INTO users (email, password_hash) VALUES (?, ?)",
            (email.strip().lower(), password_hash),
        )
        return cur.lastrowid


def get_user_by_email(db_path, email):
    with connect(db_path) as conn:
        row = conn.execute(
            "SELECT * FROM users WHERE email = ?",
            (email.strip().lower(),)).fetchone()
        return dict(row) if row else None


def get_user(db_path, user_id):
    with connect(db_path) as conn:
        row = conn.execute(
            "SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()
        return dict(row) if row else None


def delete_user(db_path, user_id):
    """Delete a user and all their data (cascades). Returns rows deleted."""
    with connect(db_path) as conn:
        cur = conn.execute("DELETE FROM users WHERE id = ?", (user_id,))
        return cur.rowcount


def orphan_course_count(db_path):
    """Pre-account courses waiting for adoption."""
    with connect(db_path) as conn:
        try:
            return conn.execute(
                "SELECT COUNT(*) AS n FROM courses WHERE user_id IS NULL"
            ).fetchone()["n"]
        except sqlite3.OperationalError:
            return 0


# --- courses ---

def add_course(db_path, user_id, name, exam_date):
    with connect(db_path) as conn:
        cur = conn.execute(
            "INSERT INTO courses (user_id, name, exam_date) VALUES (?, ?, ?)",
            (user_id, name.strip(), exam_date),
        )
        return cur.lastrowid


def list_courses(db_path, user_id):
    with connect(db_path) as conn:
        return [dict(r) for r in conn.execute(
            "SELECT * FROM courses WHERE user_id = ? ORDER BY exam_date",
            (user_id,))]


def get_course(db_path, course_id, user_id):
    """The course only if owned by user_id; else None."""
    with connect(db_path) as conn:
        row = conn.execute(
            "SELECT * FROM courses WHERE id = ? AND user_id = ?",
            (course_id, user_id)).fetchone()
        return dict(row) if row else None


def update_course(db_path, course_id, user_id, name, exam_date):
    """Update name/exam_date; returns rows updated (0 or 1)."""
    with connect(db_path) as conn:
        cur = conn.execute(
            "UPDATE courses SET name = ?, exam_date = ?"
            " WHERE id = ? AND user_id = ?",
            (name.strip(), exam_date, course_id, user_id),
        )
        return cur.rowcount


def delete_course(db_path, course_id, user_id):
    """Delete a course; topics and sessions cascade atomically.

    Returns rows deleted (0 or 1). Completed study history goes with it —
    callers must confirm with the user first.
    """
    with connect(db_path) as conn:
        cur = conn.execute(
            "DELETE FROM courses WHERE id = ? AND user_id = ?",
            (course_id, user_id))
        return cur.rowcount


def course_delete_preview(db_path, course_id, user_id):
    """Counts shown on the delete-confirmation page."""
    if get_course(db_path, course_id, user_id) is None:
        return None
    with connect(db_path) as conn:
        topics = conn.execute(
            "SELECT COUNT(*) AS n FROM topics WHERE course_id = ?",
            (course_id,)).fetchone()["n"]
        sessions = conn.execute(
            "SELECT COUNT(*) AS n, COALESCE(SUM(completed), 0) AS done"
            " FROM sessions WHERE course_id = ?", (course_id,)).fetchone()
        return {"topics": topics, "sessions": sessions["n"],
                "completed": sessions["done"]}


# --- topics ---

def _topic_owned(db_path, topic_id, user_id):
    """Topic row only if its course belongs to user_id; else None."""
    with connect(db_path) as conn:
        row = conn.execute(
            "SELECT t.* FROM topics t JOIN courses c ON t.course_id = c.id"
            " WHERE t.id = ? AND c.user_id = ?",
            (topic_id, user_id)).fetchone()
        return dict(row) if row else None


def add_topic(db_path, course_id, user_id, title, difficulty=3):
    if get_course(db_path, course_id, user_id) is None:
        return None
    difficulty = max(1, min(5, int(difficulty)))
    with connect(db_path) as conn:
        cur = conn.execute(
            "INSERT INTO topics (course_id, title, difficulty) VALUES (?, ?, ?)",
            (course_id, title.strip(), difficulty),
        )
        return cur.lastrowid


def list_topics(db_path, course_id, user_id):
    if get_course(db_path, course_id, user_id) is None:
        return []
    with connect(db_path) as conn:
        return [dict(r) for r in conn.execute(
            "SELECT * FROM topics WHERE course_id = ? ORDER BY difficulty DESC, id",
            (course_id,))]


def get_topic(db_path, topic_id, user_id):
    return _topic_owned(db_path, topic_id, user_id)


def update_topic(db_path, topic_id, user_id, title, difficulty=3):
    """Update title/difficulty; returns rows updated (0 or 1)."""
    if _topic_owned(db_path, topic_id, user_id) is None:
        return 0
    difficulty = max(1, min(5, int(difficulty)))
    with connect(db_path) as conn:
        cur = conn.execute(
            "UPDATE topics SET title = ?, difficulty = ? WHERE id = ?",
            (title.strip(), difficulty, topic_id),
        )
        return cur.rowcount


def delete_topic(db_path, topic_id, user_id):
    """Delete a topic; its sessions are kept with topic detached (SET NULL).

    Returns rows deleted (0 or 1).
    """
    if _topic_owned(db_path, topic_id, user_id) is None:
        return 0
    with connect(db_path) as conn:
        cur = conn.execute("DELETE FROM topics WHERE id = ?", (topic_id,))
        return cur.rowcount


def count_topic_sessions(db_path, topic_id, user_id):
    """Sessions referencing a topic (shown on delete confirmation)."""
    if _topic_owned(db_path, topic_id, user_id) is None:
        return 0
    with connect(db_path) as conn:
        return conn.execute(
            "SELECT COUNT(*) AS n FROM sessions WHERE topic_id = ?",
            (topic_id,)).fetchone()["n"]


# --- sessions ---

def _session_owned(db_path, session_id, user_id):
    with connect(db_path) as conn:
        row = conn.execute(
            "SELECT s.* FROM sessions s JOIN courses c ON s.course_id = c.id"
            " WHERE s.id = ? AND c.user_id = ?", (session_id, user_id)).fetchone()
        return dict(row) if row else None


def add_session(db_path, course_id, user_id, topic_id, planned_date, minutes):
    if get_course(db_path, course_id, user_id) is None:
        return None
    with connect(db_path) as conn:
        cur = conn.execute(
            "INSERT INTO sessions (course_id, topic_id, planned_date, minutes)"
            " VALUES (?, ?, ?, ?)",
            (course_id, topic_id, planned_date, minutes),
        )
        return cur.lastrowid


def list_sessions(db_path, course_id, user_id):
    if get_course(db_path, course_id, user_id) is None:
        return []
    with connect(db_path) as conn:
        return [dict(r) for r in conn.execute(
            "SELECT s.*, t.title AS topic_title FROM sessions s"
            " LEFT JOIN topics t ON s.topic_id = t.id"
            " WHERE s.course_id = ? ORDER BY s.planned_date, s.id",
            (course_id,))]


def toggle_session(db_path, session_id, user_id):
    """Flip a session's completed flag; returns rows updated (0 or 1)."""
    if _session_owned(db_path, session_id, user_id) is None:
        return 0
    with connect(db_path) as conn:
        cur = conn.execute(
            "UPDATE sessions SET completed = 1 - completed WHERE id = ?",
            (session_id,))
        return cur.rowcount


def list_sessions_for_week(db_path, user_id, start_date):
    """All sessions from start_date through six days after, across courses."""
    end = (date.fromisoformat(start_date) + timedelta(days=6)).isoformat()
    with connect(db_path) as conn:
        return [dict(r) for r in conn.execute(
            "SELECT s.*, t.title AS topic_title, c.name AS course_name"
            " FROM sessions s"
            " JOIN courses c ON s.course_id = c.id"
            " LEFT JOIN topics t ON s.topic_id = t.id"
            " WHERE c.user_id = ? AND s.planned_date BETWEEN ? AND ?"
            " ORDER BY s.planned_date, c.name, s.id",
            (user_id, start_date, end))]


def clear_pending_sessions(db_path, course_id, user_id):
    """Delete the course's unstarted sessions (finished ones are kept)."""
    if get_course(db_path, course_id, user_id) is None:
        return 0
    with connect(db_path) as conn:
        cur = conn.execute(
            "DELETE FROM sessions WHERE course_id = ? AND completed = 0",
            (course_id,))
        return cur.rowcount


# --- availability ---

DEFAULT_MINUTES = 60


def get_availability(db_path, user_id):
    """Minutes available per weekday, {0: mins, ..., 6: mins}.

    Unset weekdays fall back to DEFAULT_MINUTES.
    """
    with connect(db_path) as conn:
        rows = conn.execute(
            "SELECT weekday, minutes FROM availability WHERE user_id = ?",
            (user_id,))
        return {r["weekday"]: r["minutes"] for r in rows}


def set_availability(db_path, user_id, minutes_by_weekday):
    """Save minutes per weekday; values are clamped to >= 0."""
    with connect(db_path) as conn:
        for weekday, minutes in minutes_by_weekday.items():
            weekday = int(weekday)
            if 0 <= weekday <= 6:
                conn.execute(
                    "INSERT INTO availability (user_id, weekday, minutes)"
                    " VALUES (?, ?, ?)"
                    " ON CONFLICT(user_id, weekday)"
                    " DO UPDATE SET minutes=excluded.minutes",
                    (user_id, weekday, max(0, int(minutes))),
                )


def minutes_for(db_path, user_id, day):
    """Budget for a specific date, honoring availability (default 60)."""
    weekday = day.weekday() if isinstance(day, date) else date.fromisoformat(day).weekday()
    return get_availability(db_path, user_id).get(weekday, DEFAULT_MINUTES)


# --- data export ---

def export_user_data(db_path, user_id):
    """Everything the user owns, as plain dicts (for JSON download)."""
    data = {"courses": []}
    for course in list_courses(db_path, user_id):
        entry = dict(course)
        entry["topics"] = list_topics(db_path, course["id"], user_id)
        entry["sessions"] = list_sessions(db_path, course["id"], user_id)
        data["courses"].append(entry)
    data["availability"] = get_availability(db_path, user_id)
    user = get_user(db_path, user_id)
    data["account"] = {"email": user["email"],
                       "created_at": user["created_at"]} if user else {}
    return data
